class TestCoreInfrastructure:

    def test_0a_smoke_uniform_rates(self, fixture_data, base_gtr, tiny_dates):
        """GTR_site_specific with uniform rates + marginal dating must not crash."""
        from treetime import TreeTime
        from treetime.gtr_site_specific import GTR_site_specific
        from treetime.site_rate_loader import build_site_specific_gtr

        L = 50
        uniform_rates = np.ones(L)
        gtr_ss = build_site_specific_gtr(uniform_rates, base_gtr, seq_len=L)

        tt = TreeTime(
            gtr=gtr_ss,
            tree=str(fixture_data / "tiny.nwk"),
            aln=str(fixture_data / "tiny.fasta"),
            dates=tiny_dates,
            compress=False,
            branch_length_mode="marginal",
            verbose=0,
        )
        # branch_length_mode must be passed to run() too — run()._set_branch_length_mode()
        # can override the constructor value if 'auto' is the default.
        success = tt.run(infer_gtr=False, max_iter=1,
                         branch_length_mode='marginal', time_marginal=False)
        assert success, "TreeTime run with uniform site-specific GTR failed"

    def test_0b_zero_import_baseline(self, fixture_data, tiny_dates):
        """infer_gtr(site_specific=True) + marginal dating must not Python-crash.
        TreeTime may return success=False on toy alignments with weak temporal signal
        (known numerical fragility); we only verify the plumbing: no Python exception,
        tree is accessible, and the site-specific GTR was inferred.
        """
        from treetime import TreeTime, GTR

        tt = TreeTime(
            gtr="Jukes-Cantor",
            tree=str(fixture_data / "tiny.nwk"),
            aln=str(fixture_data / "tiny.fasta"),
            dates=tiny_dates,
            compress=False,
            branch_length_mode="marginal",
            verbose=0,
        )
        # success=False is acceptable (TreeTime catches internal optim failures gracefully)
        tt.run(infer_gtr=True, max_iter=2, branch_length_mode='marginal')

        # Plumbing check: tree is still accessible
        assert tt.tree is not None, "Tree not accessible after run"
        tips = list(tt.tree.get_terminals())
        assert len(tips) == 10, f"Expected 10 tips, got {len(tips)}"

    def test_0c_compressed_guard(self, gtr_site_specific_a):
        """prob_t_compressed must raise NotImplementedError.
        Pattern compression loses site identity, making per-site rates inapplicable.
        optimal_t_compressed is NOT overridden — the base class handles profiles=True
        (marginal mode, calls prob_t_profiles which works) and profiles=False (joint
        mode, calls prob_t_compressed which raises — intentional block).
        """
        gtr_ss = gtr_site_specific_a
        with pytest.raises(NotImplementedError, match="compressed"):
            gtr_ss.prob_t_compressed(None, None, 0.01)

    def test_0d_loader_normalization(self, fixture_data):
        """load_site_rates must produce mean-1 output from raw rates."""
        from treetime.site_rate_loader import load_site_rates
        rates, meta = load_site_rates(fixture_data / "tiny.rate")
        assert abs(meta["norm_mean"] - 1.0) < 0.01, (
            f"Normalized mean {meta['norm_mean']:.4f} != 1.0"
        )
        assert meta["n_sites"] == 50
        assert len(rates) == 50

    def test_0d_loader_invariant_policies(self, fixture_data):
        """Invariant-site policies produce expected outputs."""
        from treetime.site_rate_loader import load_site_rates
        # 'include' is default — all sites kept
        r_inc, _ = load_site_rates(fixture_data / "tiny.rate", invariant_policy='include')
        assert not np.any(np.isnan(r_inc))
        # 'epsilon' replaces near-zero rates
        r_eps, _ = load_site_rates(fixture_data / "tiny.rate", invariant_policy='epsilon')
        assert np.all(r_eps >= 1e-6)

    def test_0e_shape_correctness(self, gtr_site_specific_a):
        """GTR_site_specific shapes must be (n, L) for Pi, (L,) for mu.
        Also verifies expQt returns the 3D (n, n, L) tensor so prob_t_profiles
        takes the site-specific path (gtr.py:950: len(Qt.shape)==3).
        """
        gtr_ss = gtr_site_specific_a
        L = 50
        n = len(gtr_ss.alphabet)
        assert gtr_ss.Pi.shape == (n, L), f"Pi shape {gtr_ss.Pi.shape} != ({n},{L})"
        assert gtr_ss.mu.shape == (L,), f"mu shape {gtr_ss.mu.shape} != ({L},)"
        assert gtr_ss.expQt_interpolator is not None, "expQt_interpolator not set"
        assert abs(float(gtr_ss.mu.mean()) - 1.0) < 0.02, (
            f"mu mean {gtr_ss.mu.mean():.4f} != 1.0"
        )
        # Confirm the 3D tensor path — if this is 2D, prob_t_profiles falls back to scalar
        Qt_shape = gtr_ss.expQt(0.01).shape
        assert len(Qt_shape) == 3, (
            f"expQt must return (n,n,L) tensor for site-specific path; got {Qt_shape}"
        )
        assert Qt_shape == (n, n, L), f"expQt shape {Qt_shape} != ({n},{n},{L})"


